// maxIdentifierBytes is PostgreSQL's default identifier limit (NAMEDATALEN-1).
const maxIdentifierBytes = 63

// constraintNameHashHexLength is the length of the digest suffix used when a
// generated name does not fit in maxIdentifierBytes.
const constraintNameHashHexLength = 8

// ConstraintName derives the name of an unnamed constraint (provisional rule
// of #1803, design POSTGRES_CONSTRAINT_RENDERING_DESIGN_2026-10 4.2 / 7).
//
// Unique constraints are named "<table>_<col1>_<col2>..._key" and foreign keys
// "<table>_<col1>..._fkey": the table name without its schema and the columns
// in declared order. This is PostgreSQL's own default (ChooseConstraintName
// with ChooseIndexColumnNames / ChooseForeignKeyConstraintNameAddition), so a
// database created earlier without names carries the same name as long as it
// fits in 63 bytes and PostgreSQL did not have to add a digit.
//
// A name longer than 63 bytes is not left to PostgreSQL's truncation. The
// untruncated name is cut at a UTF-8 boundary to 54 bytes and followed by "_"
// and the first 8 lowercase hex characters of SHA-256 of the untruncated name.
// This intentionally differs from PostgreSQL, which truncates the table and
// column part instead and keeps the "_key" / "_fkey" label.
//
// The primary key stays unnamed in the Desired schema (design 4.2 option C);
// for it this returns the name PostgreSQL is expected to choose, used only to
// detect collisions.
func (RealizationPolicy) ConstraintName(kind persistence.ConstraintNameKind, table string, columns []string) string {
	switch kind {
	case persistence.ConstraintNamePrimaryKey:
		// makeObjectName keeps the label and clips the table part.
		return clipUTF8(table, maxIdentifierBytes-len("_pkey")) + "_pkey"
	case persistence.ConstraintNameUnique:
		return fitConstraintName(table + "_" + strings.Join(columns, "_") + "_key")
	case persistence.ConstraintNameForeignKey:
		return fitConstraintName(table + "_" + strings.Join(columns, "_") + "_fkey")
	default:
		return ""
	}
}

func fitConstraintName(full string) string {
	if len(full) <= maxIdentifierBytes {
		return full
	}
	sum := sha256.Sum256([]byte(full))
	suffix := hex.EncodeToString(sum[:])[:constraintNameHashHexLength]
	return clipUTF8(full, maxIdentifierBytes-1-constraintNameHashHexLength) + "_" + suffix
}

// clipUTF8 returns the longest prefix of s that is at most limit bytes and
// does not split a UTF-8 sequence.
func clipUTF8(s string, limit int) string {
	if len(s) <= limit {
		return s
	}
	cut := limit
	for cut > 0 && !utf8.RuneStart(s[cut]) {
		cut--
	}
	return s[:cut]
}

type nameOccupant struct {
	table     string
	what      string
	generated bool
}

// ConstraintNameCollisions applies PostgreSQL's namespaces: a unique
// constraint is backed by an index of the same name, so it shares the schema's
// relation namespace (pg_class) with tables, indexes and the primary key
// index; every constraint name must also be unique among the constraints of
// its table (pg_constraint). Foreign keys therefore only meet the names of
// their own table. Only collisions that involve a generated name are
// reported; the primary key's predicted name counts as generated by
// PostgreSQL and is never the reported side.
func (RealizationPolicy) ConstraintNameCollisions(tables []persistence.ConstraintNameTable) []persistence.ConstraintNameCollision {
	occupants := map[string][]nameOccupant{}
	add := func(key string, o nameOccupant) { occupants[key] = append(occupants[key], o) }
	relation := func(schema, name string) string { return "relation\x00" + schema + "\x00" + name }
	constraint := func(schema, table, name string) string {
		return "constraint\x00" + schema + "\x00" + table + "\x00" + name
	}
	for _, t := range tables {
		qualified := qualifiedTable(t.Schema, t.Table)
		add(relation(t.Schema, t.Table), nameOccupant{table: qualified, what: fmt.Sprintf("table %q", qualified)})
		for _, idx := range t.Indexes {
			add(relation(t.Schema, idx), nameOccupant{table: qualified, what: fmt.Sprintf("index %q on %s", idx, qualified)})
		}
		if t.PrimaryKey != "" {
			o := nameOccupant{table: qualified, what: fmt.Sprintf("primary key %q (PostgreSQL default) on %s", t.PrimaryKey, qualified)}
			add(relation(t.Schema, t.PrimaryKey), o)
			add(constraint(t.Schema, t.Table, t.PrimaryKey), o)
		}
		for _, uc := range t.Unique {
			o := nameOccupant{table: qualified, what: describe("unique constraint", uc, qualified), generated: uc.Generated}
			add(relation(t.Schema, uc.Name), o)
			add(constraint(t.Schema, t.Table, uc.Name), o)
		}
		for _, fk := range t.Foreign {
			add(constraint(t.Schema, t.Table, fk.Name), nameOccupant{table: qualified, what: describe("foreign key", fk, qualified), generated: fk.Generated})
		}
	}
	type reasonKey struct{ table, reason string }
	seen := map[reasonKey]struct{}{}
	var out []persistence.ConstraintNameCollision
	keys := make([]string, 0, len(occupants))
	for k := range occupants {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, key := range keys {
		list := occupants[key]
		if len(list) < 2 {
			continue
		}
		name := key[strings.LastIndex(key, "\x00")+1:]
		for i, o := range list {
			if !o.generated {
				continue
			}
			for j, other := range list {
				if i == j {
					continue
				}
				reason := fmt.Sprintf("%s collides with %s", o.what, other.what)
				k := reasonKey{o.table, reason}
				if _, dup := seen[k]; dup {
					continue
				}
				seen[k] = struct{}{}
				out = append(out, persistence.ConstraintNameCollision{Table: o.table, Name: name, Reason: reason})
			}
		}
	}
	return out
}

func describe(kind string, entry persistence.ConstraintNameEntry, table string) string {
	origin := "declared"
	if entry.Generated {
		origin = "generated"
	}
	return fmt.Sprintf("%s %q (%s) on %s", kind, entry.Name, origin, table)
}

func qualifiedTable(schema, table string) string {
	if strings.TrimSpace(schema) == "" {
		return table
	}
	return schema + "." + table
}

var _ persistence.ConstraintNamingPolicy = RealizationPolicy{}
