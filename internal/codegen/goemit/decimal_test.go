package goemit_test

import (
	"os"
	"strings"
	"testing"

	"tei/internal/codegen/goemit"
	"tei/internal/codegen/goemit/internal/stdpart"
	"tei/internal/semantic"
)

// decimalGrammar is written by hand from the grammar of operator examples:
// an optional minus sign, digits, an optional fraction, nothing else.
var decimalGrammar = []struct {
	text   string
	accept bool
}{
	{"0", true}, {"-0", true}, {"0.0", true}, {"-0.5", true}, {"300", true},
	{"1.25", true}, {"-0.01", true}, {"10", true}, {"100.500", true}, {"0.000", true},
	{"", false}, {"-", false}, {"--1", false}, {"+1", false}, {".5", false},
	{"-.5", false}, {"5.", false}, {"1.2.3", false}, {"007", false}, {"-007", false},
	{"00.5", false}, {"00", false}, {"1e3", false}, {"1E3", false}, {"1/3", false},
	{"1_000", false}, {"1,000", false}, {" 1", false}, {"1 ", false}, {"0x10", false},
	{"１", false}, {"٣", false}, {"-1-", false}, {"1-", false}, {"Inf", false}, {"NaN", false},
}

func TestParseDecimalAcceptsExactlyWhatOperatorExamplesAccept(t *testing.T) {
	for _, c := range decimalGrammar {
		got, err := stdpart.ParseDecimal(c.text)
		reference, referenceErr := semantic.ParseOperatorCaseValue(c.text)
		if (err == nil) != c.accept || (referenceErr == nil) != c.accept {
			t.Fatalf("%q: ParseDecimal err=%v, ParseOperatorCaseValue err=%v, want accept=%t",
				c.text, err, referenceErr, c.accept)
		}
		if c.accept && !sameNumber(got, reference) {
			t.Fatalf("%q: ParseDecimal=%s, ParseOperatorCaseValue=%s", c.text, got, reference)
		}
		if err != nil && referenceErr != nil && err.Error() != referenceErr.Error() {
			t.Fatalf("%q: messages differ: %q / %q", c.text, err, referenceErr)
		}
	}
}

// The emitted decimal.go is the compiled and tested part, with only the
// header and the package clause changed.
func TestEmittedDecimalFileIsTheStandardPart(t *testing.T) {
	part, err := os.ReadFile("internal/stdpart/decimal.go")
	if err != nil {
		t.Fatal(err)
	}
	out := goemit.Emit(goemit.Input{PackageName: "pricing"})
	emitted := string(out.File("decimal.go"))
	want := "// Code generated by TEI from std.decimal; DO NOT EDIT.\n\n" +
		strings.Replace(strings.ReplaceAll(string(part), "\r\n", "\n"), "package stdpart\n", "package pricing\n", 1)
	if emitted != want {
		t.Fatalf("emitted decimal.go differs from the standard part:\n%s", emitted)
	}
	if stdpart.Satisfied != "satisfied" || stdpart.NotSatisfied != "not-satisfied" || stdpart.Undecided != "undecided" {
		t.Fatal("standard Result values changed")
	}
}
