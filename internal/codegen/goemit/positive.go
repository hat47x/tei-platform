package goemit

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/printer"
	"go/token"
	"strconv"
)

// positiveFile builds the decision and check functions of one positive rule:
//
//	func QuantityIsPositive(quantity *big.Rat) bool { return quantity.Sign() > 0 }
//	func CheckQuantityIsPositive(quantity *big.Rat) Result { ... }
//
// The check function's doc comment names the attribute whose value the
// caller passes. That sentence is the only place the generated code states
// what it reads, because the code itself reads nothing.
func positiveFile(packageName string, rule Rule, names positiveNames) []byte {
	v := rule.Validation
	ruleName := " " + string(v.ID) + " "
	if rule.DisplayName != "" {
		ruleName = fmt.Sprintf("「%s」（%s）", rule.DisplayName, v.ID)
	}
	value := func() *ast.Ident { return ast.NewIdent(names.Parameter) }
	parameters := func() *ast.FieldList {
		return &ast.FieldList{List: []*ast.Field{{
			Names: []*ast.Ident{value()},
			Type:  &ast.StarExpr{X: &ast.SelectorExpr{X: ast.NewIdent("big"), Sel: ast.NewIdent("Rat")}},
		}}}
	}
	results := func(name string) *ast.FieldList {
		return &ast.FieldList{List: []*ast.Field{{Type: ast.NewIdent(name)}}}
	}
	returns := func(expr ast.Expr) *ast.BlockStmt {
		return &ast.BlockStmt{List: []ast.Stmt{&ast.ReturnStmt{Results: []ast.Expr{expr}}}}
	}

	decision := &ast.FuncDecl{
		Doc: docComment(
			fmt.Sprintf("%s は、規則%sの判定です。", names.Decision, ruleName),
			fmt.Sprintf("%s が 0 より大きいとき true を返します。", names.Parameter),
			fmt.Sprintf("値がないときの扱いは %s にあります。", names.Check),
		),
		Name: ast.NewIdent(names.Decision),
		Type: &ast.FuncType{Params: parameters(), Results: results("bool")},
		Body: returns(&ast.BinaryExpr{
			X:  &ast.CallExpr{Fun: &ast.SelectorExpr{X: value(), Sel: ast.NewIdent("Sign")}},
			Op: token.GTR,
			Y:  &ast.BasicLit{Kind: token.INT, Value: "0"},
		}),
	}
	check := &ast.FuncDecl{
		Doc: docComment(
			fmt.Sprintf("%s は、規則%sを確かめます。", names.Check, ruleName),
			fmt.Sprintf("%s には属性 %s の値を渡します。", names.Parameter, v.Attribute),
			"値がない（nil）ときは Undecided、0 より大きいときは Satisfied、それ以外は NotSatisfied を返します。",
		),
		Name: ast.NewIdent(names.Check),
		Type: &ast.FuncType{Params: parameters(), Results: results("Result")},
		Body: &ast.BlockStmt{List: []ast.Stmt{
			&ast.IfStmt{
				Cond: &ast.BinaryExpr{X: value(), Op: token.EQL, Y: ast.NewIdent("nil")},
				Body: returns(ast.NewIdent("Undecided")),
			},
			&ast.IfStmt{
				Cond: &ast.CallExpr{Fun: ast.NewIdent(names.Decision), Args: []ast.Expr{value()}},
				Body: returns(ast.NewIdent("Satisfied")),
			},
			&ast.ReturnStmt{Results: []ast.Expr{ast.NewIdent("NotSatisfied")}},
		}},
	}
	file := &ast.File{
		Name: ast.NewIdent(packageName),
		Decls: []ast.Decl{
			&ast.GenDecl{Tok: token.IMPORT, Specs: []ast.Spec{&ast.ImportSpec{
				Path: &ast.BasicLit{Kind: token.STRING, Value: strconv.Quote("math/big")},
			}}},
			decision,
			check,
		},
	}
	var body bytes.Buffer
	if err := printer.Fprint(&body, token.NewFileSet(), file); err != nil {
		panic(fmt.Sprintf("goemit: print %s: %v", names.File, err))
	}
	return withHeader(fmt.Sprintf("// Code generated by TEI from %s; DO NOT EDIT.", v.ID), body.Bytes())
}

func docComment(lines ...string) *ast.CommentGroup {
	group := &ast.CommentGroup{}
	for _, line := range lines {
		group.List = append(group.List, &ast.Comment{Text: "// " + line})
	}
	return group
}
