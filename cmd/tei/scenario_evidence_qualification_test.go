package main

import (
	"bytes"
	"encoding/json"
	"path/filepath"
	"strings"
	"testing"

	"tei/internal/scenariotest"
)

// A true Step.Verified is scoped by both executionMode and evidenceNature.
// In particular, resolving a Canonical Pattern cannot prove a provider read,
// an authorized Command, a committed effect, or a Web E2E outcome.
func TestScenarioEvidenceModeLimitsQualification(t *testing.T) {
	scenarioPath := filepath.Join("..", "..", "reference", "driver-scenarios", "order-entry-pattern-smoke.json")
	workspacePath := filepath.Join("..", "..", "reference", "workspace")
	type step struct {
		StepID         string `json:"stepId"`
		Verified       bool   `json:"verified"`
		EvidenceNature string `json:"evidenceNature"`
	}
	type receipt struct {
		ExecutionMode     string `json:"executionMode"`
		Scope             string `json:"scope"`
		SelectedStepCount int    `json:"selectedStepCount"`
		Evidence          []step `json:"evidence"`
	}
	invoke := func(args ...string) receipt {
		t.Helper()
		var out bytes.Buffer
		if err := runScenarioCommand(args, &out); err != nil {
			t.Fatalf("scenario args %q: %v", args, err)
		}
		var result receipt
		if err := json.Unmarshal(out.Bytes(), &result); err != nil {
			t.Fatalf("decode scenario receipt: %v; output=%s", err, out.String())
		}
		if !strings.Contains(result.Scope, "no Auth/Command/Web E2E") {
			t.Fatalf("scenario scope was broadened beyond synthetic reference: %q", result.Scope)
		}
		return result
	}
	pattern := func(result receipt) step {
		t.Helper()
		for _, candidate := range result.Evidence {
			if candidate.StepID == "browse-pattern" {
				return candidate
			}
		}
		t.Fatalf("browse-pattern missing from %+v", result.Evidence)
		return step{}
	}
	assertPatternResolutionOnly := func(result receipt) {
		t.Helper()
		got := pattern(result)
		if !got.Verified || got.EvidenceNature != "canonical-pattern-resolution-only" {
			t.Fatalf("verified flag was not scoped to Canonical Pattern resolution: %+v", got)
		}
	}

	static := invoke("verify", "-scenario", scenarioPath, "-workspace", workspacePath)
	if static.ExecutionMode != "static-verification" || static.SelectedStepCount != 6 {
		t.Fatalf("verify is not the six-step static reference: %+v", static)
	}
	assertPatternResolutionOnly(static)
	for _, candidate := range static.Evidence {
		if candidate.StepID == "browse-synthetic" {
			if candidate.Verified || candidate.EvidenceNature != "synthetic-fixture-bound; query-not-executed" {
				t.Fatalf("static verification incorrectly claimed query execution: %+v", candidate)
			}
		}
	}

	unpinned := invoke("run", "-scenario", scenarioPath, "-workspace", workspacePath, "-step", "browse-pattern")
	if unpinned.ExecutionMode != "exploratory-unpinned" || unpinned.SelectedStepCount != 1 {
		t.Fatalf("direct exploratory run was promoted to generated/pinned: %+v", unpinned)
	}
	assertPatternResolutionOnly(unpinned)

	var generated bytes.Buffer
	if err := runScenarioCommand([]string{"generate", "-scenario", scenarioPath, "-workspace", workspacePath}, &generated); err != nil {
		t.Fatal(err)
	}
	var plan scenariotest.Plan
	if err := json.Unmarshal(generated.Bytes(), &plan); err != nil {
		t.Fatalf("decode generated CLI plan: %v", err)
	}
	if len(plan.Commands) != 6 || plan.Commands[0].StepID != "browse-pattern" {
		t.Fatalf("unexpected generated CLI plan: %+v", plan.Commands)
	}
	pinned := invoke(plan.Commands[0].Argv[2:]...)
	if pinned.ExecutionMode != "generated-pinned" || pinned.SelectedStepCount != 1 {
		t.Fatalf("generated-pinned command has incorrect evidence scope: %+v", pinned)
	}
	assertPatternResolutionOnly(pinned)
}
