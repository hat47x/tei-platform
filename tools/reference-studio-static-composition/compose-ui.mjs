// PoC B design-time source materializer. Uses the existing #997 UI Kit resolver;
// it is not another plugin or runtime UI registry.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { resolveUICompositionKit } from '../../reference/ui-customization/composition/resolve-ui-kit.mjs';

// Trusted project-owned static import map. A fixture never supplies source paths.
const imports = Object.freeze({
  'studio.graph': Object.freeze({
    symbol: 'mountReadonlyGraph',
    path: '../../../reference/tei-studio-graph/graph.ts',
  }),
  'studio.commands': Object.freeze({
    symbol: 'mountCommandPanel',
    path: '../../../reference/tei-studio-command/command.ts',
  }),
});
const hash = bytes => createHash('sha256').update(bytes).digest('hex');

export function composeUI(raw) {
  const profile = JSON.parse(raw.toString());
  if (profile.fixtureVersion !== 'tei-studio-poc-b-reference-v0' ||
      profile.scope !== 'studio.local' || profile.services?.length !== 2 ||
      !profile.uiKit) throw new Error('invalid_poc_fixture');
  const kit = profile.uiKit;
  const implementations = Object.fromEntries(
    Object.keys(imports).map(id => [id, () => undefined]),
  );
  const resolved = resolveUICompositionKit({
    catalog: [kit], implementations,
    selected: { id: kit.id, version: kit.version },
    target: 'web', framework: { id: 'vanilla-dom', major: 1 },
  });
  const slots = Object.keys(resolved.slots).sort();
  if (slots.join(',') !== 'commands,graph') throw new Error('unsupported_ui_slots');
  const lines = [
    '// Generated by reference-studio-static-composition; DO NOT EDIT.',
    '// Read-only mount functions: Host authority and lifetimes belong to the consumer.',
  ];
  const evidence = [];
  for (const [i, slot] of slots.entries()) {
    const steps = resolved.trace[slot];
    const implementation = steps?.at(-1)?.implementation;
    const entry = imports[implementation];
    if (!entry || steps.length !== 1 || steps[0].operation !== 'provide')
      throw new Error('invalid_ui_contribution_' + slot);
    const local = 'ui' + i;
    lines.push('import { ' + entry.symbol + ' as ' + local + ' } from ' +
      JSON.stringify(entry.path) + ';');
    evidence.push({ slot, implementation, sourcePath: entry.path,
      kit: steps[0].kit, version: steps[0].version });
  }
  if (new Set(evidence.map(entry => entry.implementation)).size !== 2)
    throw new Error('duplicate_ui_component');
  lines.push('export const studioUIContributions = Object.freeze([');
  for (let i = 0; i < slots.length; i++) {
    lines.push('  Object.freeze({ slot: ' + JSON.stringify(slots[i]) +
      ', mount: ui' + i + ' }),');
  }
  lines.push(']);');
  // These are static aliases, not another runtime registry. They let the
  // existing workbench replace only its two import declarations.
  for (const [i, slot] of slots.entries()) {
    const implementation = evidence[i].implementation;
    lines.push('export const ' + imports[implementation].symbol + ' = ui' + i + ';');
  }
  lines.push('');
  const source = lines.join('\n');
  // Adjacent .d.mts is resolved for the generated .mjs by TS Bundler mode.
  // Type definitions refer to the same trusted source files as runtime imports.
  const declarations = [
    '// Generated by reference-studio-static-composition; DO NOT EDIT.',
    ...evidence.map(entry => 'export { ' + imports[entry.implementation].symbol +
      ' } from ' + JSON.stringify(imports[entry.implementation].path) + ';'),
    '',
  ].join('\n');
  return {
    source, declarations,
    provenance: {
      reference: 'tei-studio-poc-b-reference-v0',
      fixtureSha256: hash(raw), generatedSha256: hash(source),
      declarationsSha256: hash(declarations),
      uiContributions: evidence,
      authorityLimitations: [
        'ui-kit-resolution-is-design-time-only',
        'source-imports-require-available-exact-consumer-assets-and-build-lock',
        'no-browser-or-wails-rendering-was-executed',
      ],
    },
  };
}

async function main() {
  const fixture = process.argv[2];
  const outDir = process.argv[3];
  if (!fixture || !outDir) throw new Error('usage: node compose-ui.mjs FIXTURE OUT_DIR');
  const result = composeUI(await readFile(fixture));
  await mkdir(outDir, { recursive: true });
  await writeFile(resolve(outDir, 'ui.generated.mjs'), result.source);
  await writeFile(resolve(outDir, 'ui.generated.d.mts'), result.declarations);
  await writeFile(resolve(outDir, 'ui.provenance.json'),
    JSON.stringify(result.provenance, null, 2) + '\n');
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch(error => { console.error(error); process.exitCode = 1; });
}
