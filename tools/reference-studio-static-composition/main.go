// PoC-specific fixture, not an accepted TEI schema or runtime authority.
type profile struct {
	FixtureVersion string
	Scope          string
	Services       []serviceSelection
	UIKit          json.RawMessage
}
type serviceSelection struct {
	ID      string
	Version string
}

type serviceSpec struct {
	provider composition.Provider
	body     string
}

// Only trusted, compiled-in constructors can be generated. No manifest path
// becomes a Go import or arbitrary source expression.
var serviceCatalog = []serviceSpec{
	{
		provider: composition.Provider{
			ID: "studio.catalog", Scope: "studio.local",
			Offers: composition.Contract{ID: "tei.operation.workspace-catalog", Version: "0.1.0", Shape: "tei.operations.model-catalog/v0"},
		},
		body: "type CatalogService struct { root string }\n" +
			"func NewCatalogService(root string) *CatalogService { return &CatalogService{root: root} }\n" +
			"func (s *CatalogService) Catalog(namespace string) (operations.ModelCatalog, error) { return operations.CatalogWorkspace(s.root, namespace) }\n",
	},
	{
		provider: composition.Provider{
			ID: "studio.validate", Scope: "studio.local",
			Offers: composition.Contract{ID: "tei.operation.workspace-validation", Version: "0.1.0", Shape: "tei.operations.workspace-validation/v0"},
		},
		body: "type ValidateService struct { root string }\n" +
			"func NewValidateService(root string) *ValidateService { return &ValidateService{root: root} }\n" +
			"func (s *ValidateService) Validate() (operations.WorkspaceValidation, error) { return operations.ValidateWorkspace(s.root) }\n",
	},
}

type goProvenance struct {
	Reference            string   `json:"reference"`
	FixtureSHA256        string   `json:"fixtureSha256"`
	GeneratedSHA256      string   `json:"generatedSha256"`
	RegistryRevision     uint64   `json:"registryRevision"`
	ServiceOrder         []string `json:"serviceOrder"`
	AuthorityLimitations []string `json:"authorityLimitations"`
}

func digest(b []byte) string {
	sum := sha256.Sum256(b)
	return hex.EncodeToString(sum[:])
}

func composeServices(raw []byte) ([]byte, goProvenance, error) {
	var p profile
	if err := json.Unmarshal(raw, &p); err != nil {
		return nil, goProvenance{}, err
	}
	if p.FixtureVersion != "tei-studio-poc-b-reference-v0" || p.Scope != "studio.local" ||
		(len(p.UIKit) == 0 || string(p.UIKit) == "null") || len(p.Services) != 2 {
		return nil, goProvenance{}, errors.New("unsupported or incomplete PoC B fixture")
	}
	known := make(map[string]serviceSpec, len(serviceCatalog))
	providers := make([]composition.Provider, 0, len(serviceCatalog))
	for _, candidate := range serviceCatalog {
		known[candidate.provider.ID] = candidate
		providers = append(providers, candidate.provider)
	}
	registry := composition.NewRegistry()
	snapshot, err := registry.Apply(0, providers, nil)
	if err != nil {
		return nil, goProvenance{}, fmt.Errorf("existing composition resolver: %w", err)
	}
	seen := make(map[string]bool, len(p.Services))
	requirements := make([]composition.WiringRequirement, 0, len(p.Services))
	for _, selected := range p.Services {
		if seen[selected.ID] {
			return nil, goProvenance{}, fmt.Errorf("duplicate service %q", selected.ID)
		}
		seen[selected.ID] = true
		spec, ok := known[selected.ID]
		if !ok {
			return nil, goProvenance{}, fmt.Errorf("unknown service %q", selected.ID)
		}
		if selected.Version != spec.provider.Offers.Version {
			return nil, goProvenance{}, fmt.Errorf("incompatible version %q for %s", selected.Version, selected.ID)
		}
		requirements = append(requirements, composition.WiringRequirement{
			Contract: spec.provider.Offers, ProviderID: selected.ID,
			Scope: p.Scope, SlotID: selected.ID,
		})
	}
	wiring := registry.InspectWiringSet(requirements)
	if wiring.Verdict != composition.ProposalCandidate {
		return nil, goProvenance{}, fmt.Errorf("existing composition resolver rejected wiring: %v", wiring.Verdict)
	}
	for _, finding := range wiring.Findings {
		if finding.Verdict != composition.ProposalCandidate || finding.Selected == nil {
			return nil, goProvenance{}, fmt.Errorf("unresolved service wiring: %s", finding.Reason)
		}
	}
	var output strings.Builder
	output.WriteString("// Code generated by reference-studio-static-composition; DO NOT EDIT.\n")
	output.WriteString("// Design-time Reference; this file grants no invocation authority.\n")
	output.WriteString("package staticservices\n\nimport \"tei/internal/operations\"\n\n")
	order := make([]string, 0, len(p.Services))
	construction := make([]string, 0, len(p.Services))
	for _, id := range snapshot.ActivationOrder {
		if !seen[id] {
			continue
		}
		order = append(order, id)
		output.WriteString(known[id].body)
		output.WriteByte('\n')
		switch id {
		case "studio.catalog":
			construction = append(construction, "NewCatalogService(root)")
		case "studio.validate":
			construction = append(construction, "NewValidateService(root)")
		}
	}
	if len(order) != 2 {
		return nil, goProvenance{}, errors.New("resolved service set is incomplete")
	}
	output.WriteString("// Services returns an explicit, statically linked list. A trusted Host owns root and admission.\n")
	output.WriteString("func Services(root string) []any { return []any{" + strings.Join(construction, ", ") + "} }\n")
	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return nil, goProvenance{}, err
	}
	return formatted, goProvenance{
		Reference:     "tei-studio-poc-b-reference-v0",
		FixtureSHA256: digest(raw), GeneratedSHA256: digest(formatted),
		RegistryRevision: snapshot.Revision, ServiceOrder: order,
		AuthorityLimitations: []string{
			"declaration-eligibility-is-not-conformance-or-artifact-attestation",
			"host-must-enforce-current-identity-workspace-and-resource-permissions",
			"generated-services-have-not-been-bound-to-wails-host",
		},
	}, nil
}

func main() {
	fixture := flag.String("fixture", "tools/reference-studio-static-composition/fixture.json", "PoC selection fixture")
	outDir := flag.String("out", "", "output directory (required)")
	flag.Parse()
	if *outDir == "" {
		fmt.Fprintln(os.Stderr, "-out is required")
		os.Exit(2)
	}
	raw, err := os.ReadFile(*fixture)
	if err == nil {
		var source []byte
		var provenance goProvenance
		source, provenance, err = composeServices(raw)
		if err == nil {
			var meta []byte
			meta, err = json.MarshalIndent(provenance, "", "  ")
			if err == nil {
				err = os.MkdirAll(*outDir, 0755)
			}
			if err == nil {
				err = os.WriteFile(filepath.Join(*outDir, "services.generated.go"), source, 0644)
			}
			if err == nil {
				err = os.WriteFile(filepath.Join(*outDir, "services.provenance.json"), append(meta, '\n'), 0644)
			}
		}
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
