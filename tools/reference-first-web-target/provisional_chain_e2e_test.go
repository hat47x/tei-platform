// fileEvidenceSink appends each Evidence as one JSON line, so the parent test
// can read what the Web process's Runner produced.
type fileEvidenceSink struct {
	mu   sync.Mutex
	path string
}

func (s *fileEvidenceSink) Record(ev effectcommit.Evidence) {
	raw, err := json.Marshal(ev)
	if err != nil {
		return
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	f, err := os.OpenFile(s.path, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0o600)
	if err != nil {
		return
	}
	defer f.Close()
	_, _ = f.Write(append(raw, '\n'))
}

func readEvidenceLines(t *testing.T, path string) []effectcommit.Evidence {
	t.Helper()
	f, err := os.Open(path)
	if os.IsNotExist(err) {
		return nil
	}
	if err != nil {
		t.Fatal(err)
	}
	defer f.Close()
	var out []effectcommit.Evidence
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		var ev effectcommit.Evidence
		if err := json.Unmarshal(scanner.Bytes(), &ev); err != nil {
			t.Fatal(err)
		}
		out = append(out, ev)
	}
	return out
}

