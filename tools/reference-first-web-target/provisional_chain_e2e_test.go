type chainChild struct {
	base     string
	pid      int
	evidence string
	stop     func() string // returns the process log
}

func (r *chainRun) command(ctx context.Context, root, address string, extraEnv ...string) (*exec.Cmd, string) {
	r.seq++
	evidence := filepath.Join(r.t.TempDir(), fmt.Sprintf("evidence-%d.jsonl", r.seq))
	args := []string{"-test.run=^TestProvisionalChainWebChild$", "--", "-workspace", root, "-application", "order_entry",
		"-baseline-id", "B", "-baseline-revision", testBaselineRevision, "-target-revision", testTargetRevision, "-listen", address,
		"-host-acceptance-store", r.storeDir, "-host-acceptance-trust", r.trust,
		"-provisional-effect-grant", r.prov.grantPath, "-provisional-effect-grant-trust", r.prov.trustPath,
		"-provisional-effect-grant-development-only"}
	command := exec.CommandContext(ctx, r.exe, args...)
	command.Dir = r.repoRoot
	command.Env = append(os.Environ(),
		chainChildStore+"=1", chainChildTrust+"="+r.trust, chainChildGrant+"="+r.prov.grantPath,
		chainChildGrantTrus+"="+r.prov.trustPath, chainChildEvidence+"="+evidence)
	command.Env = append(command.Env, extraEnv...)
	return command, evidence
}

func (r *chainRun) start(root string, extraEnv ...string) chainChild {
	t := r.t
	t.Helper()
	address := freeAddress(t)
	ctx, cancel := context.WithCancel(context.Background())
	command, evidence := r.command(ctx, root, address, extraEnv...)
	var log bytes.Buffer
	command.Stdout, command.Stderr = &log, &log
	if err := command.Start(); err != nil {
		cancel()
		t.Fatal(err)
	}
	done := make(chan error, 1)
	go func() { done <- command.Wait() }()
	stopped := false
	stop := func() string {
		if !stopped {
			stopped = true
			cancel()
			<-done
		}
		return redactDSN(log.String())
	}
	t.Cleanup(func() { stop() })
	base := "http://" + address
	client := &http.Client{Timeout: time.Second}
	for deadline := time.Now().Add(90 * time.Second); ; time.Sleep(50 * time.Millisecond) {
		if response, err := client.Get(base + "/healthz"); err == nil {
			response.Body.Close()
			if response.StatusCode == http.StatusOK {
				return chainChild{base: base, pid: command.Process.Pid, evidence: evidence, stop: stop}
			}
		}
		if time.Now().After(deadline) {
			text := stop()
			t.Fatalf("Web child did not serve HTTP: %s", text)
		}
	}
}

func (r *chainRun) refuse(root, code string, extraEnv ...string) []byte {
	t := r.t
	t.Helper()
	address := freeAddress(t)
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	command, _ := r.command(ctx, root, address, extraEnv...)
	output, err := command.CombinedOutput()
	var exit *exec.ExitError
	if !asExitError(err, &exit) || exit.ExitCode() != 2 || !bytes.Contains(output, []byte(code)) {
		t.Fatalf("expected the Web process to refuse with %s before HTTP: err=%v output=%s", code, err, redactDSN(string(output)))
	}
	return output
}

func asExitError(err error, target **exec.ExitError) bool {
	if e, ok := err.(*exec.ExitError); ok {
		*target = e
		return true
	}
	return false
}

