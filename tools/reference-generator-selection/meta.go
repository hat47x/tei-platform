package generatorselection

import (
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"go/format"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"time"
)

// MetaOptions describes a candidate produced by an externally supplied
// generator. The generator is depth 1: TEI runs it once and does not allow it
// to generate another generator in this PoC.
type MetaOptions struct {
	ID                  string
	Provider            string
	Model               string
	ContractPath        string
	GeneratorSourcePath string
	PromptPath          string
	ContextPath         string
	OutDir              string
	Note                string
	Timeout             time.Duration
}

func runMetaGenerator(ctx context.Context, generatorSource []byte, contractPath string, timeout time.Duration) ([]byte, error) {
	tempDir, err := os.MkdirTemp("", "tei-generator-meta-*")
	if err != nil {
		return nil, err
	}
	defer os.RemoveAll(tempDir)
	if err := os.WriteFile(filepath.Join(tempDir, "main.go"), generatorSource, 0o644); err != nil {
		return nil, err
	}
	binaryPath := candidateBinaryPath(filepath.Join(tempDir, "generator"))
	buildCtx, cancel := context.WithTimeout(ctx, timeout)
	defer cancel()
	if err := buildCandidate(buildCtx, tempDir, binaryPath); err != nil {
		return nil, fmt.Errorf("build generator: %w", err)
	}
	runCtx, cancelRun := context.WithTimeout(ctx, timeout)
	defer cancelRun()
	cmd := exec.CommandContext(runCtx, binaryPath, "-contract", contractPath)
	raw, err := cmd.Output()
	if err != nil {
		var exit *exec.ExitError
		if errors.As(err, &exit) {
			return nil, fmt.Errorf("generator exited %d: %s", exit.ExitCode(), string(exit.Stderr))
		}
		return nil, err
	}
	formatted, err := format.Source(raw)
	if err != nil {
		return nil, fmt.Errorf("generator output is not valid Go: %w", err)
	}
	if len(formatted) == 0 {
		return nil, fmt.Errorf("generator output is empty")
	}
	return formatted, nil
}

// GenerateWithMetaGenerator runs one externally supplied generator and records
// the candidate it produced together with the generator source and prompt /
// context provenance.
func GenerateWithMetaGenerator(ctx context.Context, opts MetaOptions) (CandidateManifest, error) {
	if strings.TrimSpace(opts.ID) == "" || strings.TrimSpace(opts.Provider) == "" || strings.TrimSpace(opts.Model) == "" {
		return CandidateManifest{}, fmt.Errorf("id, provider, and model are required")
	}
	if strings.TrimSpace(opts.ContractPath) == "" || strings.TrimSpace(opts.GeneratorSourcePath) == "" {
		return CandidateManifest{}, fmt.Errorf("contract and generator source are required")
	}
	if strings.TrimSpace(opts.PromptPath) == "" || strings.TrimSpace(opts.ContextPath) == "" {
		return CandidateManifest{}, fmt.Errorf("prompt and context are required")
	}
	if strings.TrimSpace(opts.OutDir) == "" {
		return CandidateManifest{}, fmt.Errorf("out is required")
	}
	var contract Contract
	if _, err := readJSON(opts.ContractPath, &contract); err != nil {
		return CandidateManifest{}, err
	}
	if err := validateContract(contract); err != nil {
		return CandidateManifest{}, err
	}
	contractRaw, err := os.ReadFile(opts.ContractPath)
	if err != nil {
		return CandidateManifest{}, err
	}
	generatorSource, err := os.ReadFile(opts.GeneratorSourcePath)
	if err != nil {
		return CandidateManifest{}, err
	}
	prompt, err := os.ReadFile(opts.PromptPath)
	if err != nil {
		return CandidateManifest{}, err
	}
	contextRaw, err := os.ReadFile(opts.ContextPath)
	if err != nil {
		return CandidateManifest{}, err
	}
	absoluteContract, err := filepath.Abs(opts.ContractPath)
	if err != nil {
		return CandidateManifest{}, err
	}
	timeout := opts.Timeout
	if timeout <= 0 {
		timeout = 2 * time.Minute
	}
	source, err := runMetaGenerator(ctx, generatorSource, absoluteContract, timeout)
	if err != nil {
		return CandidateManifest{}, err
	}
	if _, err := os.Lstat(opts.OutDir); err == nil {
		return CandidateManifest{}, fmt.Errorf("output directory already exists: %s", opts.OutDir)
	} else if !os.IsNotExist(err) {
		return CandidateManifest{}, err
	}
	if err := os.MkdirAll(filepath.Dir(opts.OutDir), 0o755); err != nil {
		return CandidateManifest{}, err
	}
	if err := os.Mkdir(opts.OutDir, 0o755); err != nil {
		return CandidateManifest{}, err
	}
	cleanup := func() { _ = os.RemoveAll(opts.OutDir) }
	writes := []struct {
		name    string
		content []byte
	}{
		{"main.go", source},
		{"generator.go", generatorSource},
		{"prompt.txt", prompt},
		{"context.json", contextRaw},
	}
	for _, write := range writes {
		if err := os.WriteFile(filepath.Join(opts.OutDir, write.name), write.content, 0o644); err != nil {
			cleanup()
			return CandidateManifest{}, err
		}
	}
	note := opts.Note
	if note == "" {
		note = "candidate generated by an externally supplied generator (depth 1)"
	}
	manifest := CandidateManifest{
		Schema: CandidateSchema, ID: opts.ID, Version: "1", Origin: "generated-ai",
		Source: "main.go", SourceDigest: digest(source), Note: note,
		Generation: &GenerationProvenance{
			Provider: opts.Provider, Model: opts.Model, ContractDigest: digest(contractRaw),
			PromptDigest: digest(prompt), ContextDigest: digest(contextRaw), OutputDigest: digest(source),
			PromptPath: "prompt.txt", ContextPath: "context.json",
		},
		Lineage: &Lineage{
			Depth: 1, GeneratorSource: "generator.go", GeneratorSourceDigest: digest(generatorSource),
			GeneratorOrigin: "generated-ai",
		},
	}
	raw, err := json.MarshalIndent(manifest, "", "  ")
	if err != nil {
		cleanup()
		return CandidateManifest{}, err
	}
	raw = append(raw, '\n')
	if err := os.WriteFile(filepath.Join(opts.OutDir, "candidate.json"), raw, 0o644); err != nil {
		cleanup()
		return CandidateManifest{}, err
	}
	return manifest, nil
}
