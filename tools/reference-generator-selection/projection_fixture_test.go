package generatorselection

import (
	"context"
	"encoding/json"
	"os"
	"path/filepath"
	"reflect"
	"testing"
)

// #2488: a record/string projection contract has a generator family and a
// conformance fixture that distinguishes present, empty, missing and
// unresolved. The generated source digest and generator provenance are
// recorded, and the fixture is executed against the built candidate, not just
// inspected as text.
func TestProjectionConformanceFixtures(t *testing.T) {
	cases := []struct {
		name     string
		dir      string
		strategy string
	}{
		{name: "text", dir: "sui-text", strategy: "text-template"},
		{name: "record", dir: "sui-record", strategy: "text-record-template"},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			runProjectionFixture(t, tc.dir, tc.strategy)
		})
	}
}

func runProjectionFixture(t *testing.T, dir, strategy string) {
	t.Helper()
	contractPath := filepath.Join("testdata", dir, "contract.json")
	fixturePath := filepath.Join("testdata", dir, "fixtures.json")
	out := filepath.Join(t.TempDir(), "candidate")
	generated, err := Generate(contractPath, strategy, out)
	if err != nil {
		t.Fatal(err)
	}
	if generated.SourceDigest == "" || generated.Manifest.SourceDigest != generated.SourceDigest {
		t.Fatalf("source digest not recorded: %+v", generated)
	}
	if generated.Manifest.Generator == nil ||
		generated.Manifest.Generator.Strategy != strategy ||
		generated.Manifest.Generator.ContractDigest == "" {
		t.Fatalf("generator provenance not recorded: %+v", generated.Manifest)
	}
	source, err := os.ReadFile(filepath.Join(out, "main.go"))
	if err != nil {
		t.Fatal(err)
	}
	if digest(source) != generated.SourceDigest {
		t.Fatalf("source digest does not match the generated bytes")
	}

	raw, err := os.ReadFile(fixturePath)
	if err != nil {
		t.Fatal(err)
	}
	var fixture Fixture
	if err := json.Unmarshal(raw, &fixture); err != nil {
		t.Fatal(err)
	}
	if len(fixture.Cases) == 0 {
		t.Fatal("fixture has no cases")
	}

	binary := candidateBinaryPath(filepath.Join(t.TempDir(), "candidate"))
	if err := buildCandidate(context.Background(), out, binary); err != nil {
		t.Fatal(err)
	}
	for _, testCase := range fixture.Cases {
		got, _, err := runCandidate(context.Background(), binary, testCase.Input, ExecutionOptions{})
		if err != nil {
			t.Errorf("%s: %v", testCase.ID, err)
			continue
		}
		if !reflect.DeepEqual(got, testCase.Want) {
			t.Errorf("%s: got %+v want %+v", testCase.ID, got, testCase.Want)
		}
	}
}
