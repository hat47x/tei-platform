package teimdreader

import (
	"fmt"
	"go/format"
	"go/token"
	"regexp"
	"sort"
	"strings"
)

// EdgeCodeOrigin retains the original source cells used by a generated edge.
// It is a reference witness, not a provenance or meaning acceptance certificate.
type EdgeCodeOrigin struct {
	EdgeID     string
	IDSource   Span
	FromSource Span
	ToSource   Span
}

// GeneratedOutgoingGo contains executable Go source and the original cell
// locations. A layout-only change may alter Origins but not Code.
type GeneratedOutgoingGo struct {
	Code    []byte
	Origins []EdgeCodeOrigin
}

var referencePackageName = regexp.MustCompile("^[A-Za-z_][A-Za-z0-9_]*$")

// GenerateOutgoingGo compiles an *unaccepted reference Candidate* into a
// self-contained Go function. This does not select a TEI Language Plugin,
// admit semantic meaning, or build a real Plugin artifact.
//
// The generated Outgoing function implements the edge selection itself;
// it does not delegate the graph behavior to handwritten Go.
func GenerateOutgoingGo(c Candidate, packageName string) (GeneratedOutgoingGo, error) {
	if !referencePackageName.MatchString(packageName) || token.Lookup(packageName).IsKeyword() {
		return GeneratedOutgoingGo{}, fmt.Errorf("invalid Go package name %q", packageName)
	}
	if len(c.Nodes) == 0 || len(c.Edges) == 0 {
		return GeneratedOutgoingGo{}, fmt.Errorf("reference graph must contain nodes and edges")
	}

	nodes := append([]Node(nil), c.Nodes...)
	sort.Slice(nodes, func(i, j int) bool { return nodes[i].ID < nodes[j].ID })
	nodeIDs := make(map[string]struct{}, len(nodes))
	for _, n := range nodes {
		if n.ID == "" {
			return GeneratedOutgoingGo{}, fmt.Errorf("empty node ID")
		}
		if _, exists := nodeIDs[n.ID]; exists {
			return GeneratedOutgoingGo{}, fmt.Errorf("duplicate node ID %q", n.ID)
		}
		nodeIDs[n.ID] = struct{}{}
	}

	edges := append([]Edge(nil), c.Edges...)
	sort.Slice(edges, func(i, j int) bool { return edges[i].ID < edges[j].ID })
	outgoing := make(map[string][]string, len(nodes))
	seenEdges := make(map[string]struct{}, len(edges))
	origins := make([]EdgeCodeOrigin, 0, len(edges))
	for _, e := range edges {
		if e.ID == "" {
			return GeneratedOutgoingGo{}, fmt.Errorf("empty edge ID")
		}
		if _, exists := seenEdges[e.ID]; exists {
			return GeneratedOutgoingGo{}, fmt.Errorf("duplicate edge ID %q", e.ID)
		}
		seenEdges[e.ID] = struct{}{}
		if _, ok := nodeIDs[e.From]; !ok {
			return GeneratedOutgoingGo{}, fmt.Errorf("unknown source node %q for edge %q", e.From, e.ID)
		}
		if _, ok := nodeIDs[e.To]; !ok {
			return GeneratedOutgoingGo{}, fmt.Errorf("unknown target node %q for edge %q", e.To, e.ID)
		}
		outgoing[e.From] = append(outgoing[e.From], e.ID)
		origins = append(origins, EdgeCodeOrigin{
			EdgeID: e.ID, IDSource: e.IDSource, FromSource: e.FromSource, ToSource: e.ToSource,
		})
	}

	var b strings.Builder
	b.WriteString("// Code generated by the TEI Markdown Graph reference generator; DO NOT EDIT.\n")
	b.WriteString("// Reference fixture only: not a selected TEI Language Plugin or accepted meaning.\n")
	fmt.Fprintf(&b, "package %s\n\n", packageName)
	b.WriteString("// Outgoing returns sorted edge IDs from the specified node.\n")
	b.WriteString("// An unknown node returns nil; a known node without edges returns an empty slice.\n")
	b.WriteString("func Outgoing(nodeID string) []string {\n\tswitch nodeID {\n")
	for _, n := range nodes {
		fmt.Fprintf(&b, "\tcase %q:\n\t\treturn []string{", n.ID)
		for i, edgeID := range outgoing[n.ID] {
			if i > 0 {
				b.WriteString(", ")
			}
			fmt.Fprintf(&b, "%q", edgeID)
		}
		b.WriteString("}\n")
	}
	b.WriteString("\tdefault:\n\t\treturn nil\n\t}\n}\n\n")
	b.WriteString("// OutgoingCount returns the number of outgoing edges.\n")
	b.WriteString("func OutgoingCount(nodeID string) int { return len(Outgoing(nodeID)) }\n")

	compiled, err := format.Source([]byte(b.String()))
	if err != nil {
		return GeneratedOutgoingGo{}, fmt.Errorf("generated Go is invalid: %w", err)
	}
	return GeneratedOutgoingGo{Code: compiled, Origins: origins}, nil
}
